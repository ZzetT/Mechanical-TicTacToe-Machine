def create_stand_platform():
    with BuildPart() as p:
        # Base platform
        with BuildSketch(Plane.XY):
            RectangleRounded(stand_outer_width, stand_outer_depth, stand_corner_radius)
        extrude(amount=stand_bottom_thickness)
        
        # Border
        with BuildSketch(Plane.XY.offset(stand_bottom_thickness)):
            RectangleRounded(stand_outer_width, stand_outer_depth, stand_corner_radius)
            Rectangle(stand_inner_width, stand_inner_depth, mode=Mode.SUBTRACT)
        extrude(amount=stand_border_height)
        
        # Fillet top edges of the border
        top_face = p.faces().sort_by(Axis.Z)[-1]
        fillet(top_face.edges(), radius=stand_top_fillet_radius)
        
        # Holes for legs
        hole_x_offset = stand_outer_width / 2.0 - stand_border_thickness - stand_leg_diameter / 2.0 - stand_leg_hole_margin
        hole_y_offset = stand_outer_depth / 2.0 - stand_border_thickness - stand_leg_diameter / 2.0 - stand_leg_hole_margin
        with BuildSketch(Plane.XY):
            with Locations(
                (hole_x_offset, hole_y_offset),
                (-hole_x_offset, hole_y_offset),
                (hole_x_offset, -hole_y_offset),
                (-hole_x_offset, -hole_y_offset)
            ):
                Circle(radius=stand_leg_diameter/2.0 + stand_leg_tolerance)
        extrude(amount=stand_leg_hole_depth, mode=Mode.SUBTRACT)
        
    p.part.label = "stand_platform"
    return p.part

