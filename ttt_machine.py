class SliderPosition(Enum):
    SLIDER_LEFT = 0
    SLIDER_RIGHT = 1
    SLIDER_CENTER = 2
    SLIDER_DONT_CARE = 3
    SLIDER_NOT_X = 4
    SLIDER_NOT_O = 5      




def create_field_sketch(position, slider, move_while_shifting):
    """Creates the sketch for a single field in the Tic Tac Toe board.

    For compound symbols ('*' = not X -> LEFT|CENTER, '!' = not O -> RIGHT|CENTER)
    a single merged cutout is produced instead of two overlapping ones, so no
    thin-wall artifacts remain between the two fall slots.
    """

    # --- parameters for the fall-slot (the vertical "drop" part) -------------
    # For the simple cases we only have ONE drop slot.
    # For the compound cases we need TWO drop openings joined by a horizontal
    # bridge at the bottom rail level, so the solid bit that would otherwise
    # sit between them disappears.
    fall_slots = []  # list of (x_offset_of_slot_left_edge, width)

    match slider:
        case SliderPosition.SLIDER_LEFT:
            fall_x = margin_horizontal
            fall_slots = [(fall_x, slot_width)]
            top_rect_width = shift_left_distance + slot_width + right_shift_clearance
            top_rect_offset = margin_horizontal

        case SliderPosition.SLIDER_CENTER:
            fall_x = field_width / 2 - slot_width / 2
            fall_slots = [(fall_x, slot_width)]
            if move_while_shifting:
                top_rect_width = slot_width
            else:
                top_rect_width = slot_width + shift_left_distance + bottom_shift_distance + right_shift_clearance
            top_rect_offset = field_width / 2 - slot_width / 2

        case SliderPosition.SLIDER_RIGHT | SliderPosition.SLIDER_DONT_CARE:
            fall_x = field_width - margin_horizontal - slot_width
            fall_slots = [(fall_x, slot_width)]
            top_rect_width = shift_left_distance + slot_width + right_shift_clearance
            top_rect_offset = fall_x

        case SliderPosition.SLIDER_NOT_X:
            # '*' : slider sits at LEFT or CENTER
            left_x   = margin_horizontal
            center_x = field_width / 2 - slot_width / 2
            fall_slots = [(left_x, slot_width), (center_x, slot_width)]
            # Top shift corridor must cover the full LEFT fall slot all the
            # way to whatever the CENTER case would cover.
            top_rect_offset = margin_horizontal
            if move_while_shifting:
                top_right_edge = center_x + slot_width
            else:
                top_right_edge = center_x + slot_width + shift_left_distance + bottom_shift_distance + right_shift_clearance
            top_rect_width = top_right_edge - top_rect_offset

        case SliderPosition.SLIDER_NOT_O:
            # '!' : slider sits at RIGHT or CENTER
            center_x = field_width / 2 - slot_width / 2
            right_x  = field_width - margin_horizontal - slot_width
            fall_slots = [(center_x, slot_width), (right_x, slot_width)]
            top_rect_offset = center_x
            # Right-most edge is the right fall slot's right edge plus the
            # shift-left allowance (same semantics as SLIDER_RIGHT).
            top_right_edge = right_x + slot_width + shift_left_distance + right_shift_clearance
            # Cap at the original RIGHT behaviour if that would be narrower
            top_rect_width = top_right_edge - top_rect_offset

    with Locations((-card_width / 2 + (position % 3) * field_width,
                    card_height / 6 - (position // 3) * field_height)) as l:

        if slider == SliderPosition.SLIDER_DONT_CARE:
            with Locations((margin_horizontal, margin_vertical)):
                Rectangle(bottom_slot_width, slot_height + height_of_fall,
                          align=(Align.MIN, Align.MIN))
        else:
            # --- bottom rectangle (slider travel rail) ----------------------
            with Locations((margin_horizontal, margin_vertical)):
                Rectangle(bottom_slot_width, slot_height,
                          align=(Align.MIN, Align.MIN))

            # --- fall slot(s) -----------------------------------------------
            # For compound symbols we emit one *single* rectangle that spans
            # from the left edge of the left-most fall opening to the right
            # edge of the right-most one, but only as tall as the "fall"
            # region that is actually shared.  To avoid a wall between two
            # openings we simply union a bridging rectangle at the bottom.
            fall_y = margin_vertical + slot_height
            fall_h = height_of_fall - slot_height

            # Build the fall slot(s) and remember the bottom vertices of each
            # individual slot rectangle BEFORE the subsequent bridge union —
            # those are exactly the re-entrant corners where the fall slot
            # meets the bottom rail.
            bottom_ref_verts = []

            for fx, fw in fall_slots:
                with Locations((fx, fall_y)):
                    r = Rectangle(fw, fall_h, align=(Align.MIN, Align.MIN))
                # The two lowest vertices of this rectangle are its
                # bottom-left / bottom-right corners in world coordinates.
                bottom_ref_verts.extend(r.vertices().sort_by(Axis.Y)[:2])

            # Bridge for compound cases so no artifact remains in between.
            if len(fall_slots) > 1:
                left_edge  = min(fx for fx, _ in fall_slots)
                right_edge = max(fx + fw for fx, fw in fall_slots)
                with Locations((left_edge, fall_y)):
                    Rectangle(right_edge - left_edge, fall_h,
                              align=(Align.MIN, Align.MIN))

            # --- fillet the fall-slot ↔ bottom-rail corners -----------------
            # After all the unions, look for vertices in the final sketch
            # that coincide with any of our remembered bottom-corner points.
            # Corners that got absorbed by the bridge simply won't be found
            # and are silently skipped.
            corners_to_fillet = [
                v for v in vertices()
                if any((v.X - bv.X) ** 2 + (v.Y - bv.Y) ** 2 < 1e-4
                       for bv in bottom_ref_verts)
            ]

            if corners_to_fillet:
                fillet(corners_to_fillet, radius=1.4)

        # --- top rectangle (shift-left corridor) -----------------------------
        with Locations((top_rect_offset, margin_vertical + height_of_fall)):
            # For compound symbols the little triangular "ramp" on the left
            # side should start at the left-most fall slot, same as in the
            # simple cases — that is already the case because top_rect_offset
            # is aligned to the first fall slot.
            Polygon([
                (0, 0),
                (0, slot_height),
                (top_rect_width, slot_height),
                (top_rect_width, 0),
                (slot_width, -height_of_fall + slot_height + 5),
            ], align=None)

    return l

def state_to_filename(state, move, card_number=""):
    """Converts a board state, move, and optional card number into a filename-safe string."""
    # Replace characters that are problematic in filenames.
    # '?' -> 'q' (for query/question)
    # '.' -> 'd' (for dot)
    # ' ' -> 's' (for space/empty)
    # '!' -> 'ex' (for exclamation)
    # '*' -> 'st' (for star)
    safe_state = state.replace('?', 'q').replace('.', 'd').replace(' ', 's').replace('!', 'ex').replace('*', 'st')
    if str(card_number) != "":
        return f"card_{card_number}_{safe_state}_move_{move}"
    return f"card_{safe_state}_move_{move}"

def create_card(state, best_move, card_number=""):
    with BuildPart() as card:
        Box(total_card_width, card_height, card_depth)  
        fillet(card.edges().filter_by(Axis.Z), radius=card_corner_radius)
        with BuildSketch(card.faces().sort_by().last) as s:
            with Locations((-(total_card_width)/2+ card_width/3, 0)):
                with GridLocations(x_spacing=card_width/3, y_spacing=0, x_count=3, y_count=1, align=(Align.MIN, Align.MIN)):
                    Rectangle(0.01, card_height)                   
            with Locations((-extra_space_to_right/2, 0)):
                with GridLocations(x_spacing=0, y_spacing=card_height/3, x_count=1, y_count=2):
                    Rectangle(card_width, 0.01)                
         
                for pos, char in enumerate(state):
                    if char == 'X':
                        slider = SliderPosition.SLIDER_RIGHT
                    elif char == 'O':
                        slider = SliderPosition.SLIDER_LEFT
                    elif char == '.' or char == ' ':
                        slider = SliderPosition.SLIDER_CENTER
                    elif char == '?':
                        slider = SliderPosition.SLIDER_DONT_CARE
                    elif char == '!':
                        slider = SliderPosition.SLIDER_NOT_O
                    elif char == '*':
                        slider = SliderPosition.SLIDER_NOT_X
                    else:
                        continue

                    create_field_sketch(pos, slider, pos == best_move)

        extrude(amount=-card_depth, mode=Mode.SUBTRACT)
        with Locations((total_card_width/2, 0, -card_depth/2)):
            Box(shift_left_distance+2, height_of_fall-1, card_depth, align=(Align.MIN, Align.CENTER)) 
        
        fillet(card.edges().filter_by(Axis.Z).filter_by_position(Axis.X, total_card_width/2 - 0.1, 1000), radius=card_corner_radius)
            
        if str(card_number) != "":
            with BuildSketch(Plane.XY):
                with Locations((total_card_width/2 + (shift_left_distance)/2-1, 0)):
                    Text(str(card_number), font_size=11)
            extrude(amount=card_depth, mode=Mode.SUBTRACT)
                        
        # Little slot for card holding rod
        with Locations((-total_card_width/2, -field_height/2, -card_depth/2)):
            Box(shift_left_distance+2, 4, card_depth, align=(Align.MIN, Align.CENTER), mode=Mode.SUBTRACT)        
    card.part.label = state_to_filename(state, best_move, card_number)
    return card    

