def create_fluted_knob():
    with BuildPart() as p:
        # 1. Create the scalloped profile
        with BuildSketch(Plane.XY):
            # Base circle
            Circle(radius=fluted_knob_diameter / 2)
            
            # Cut out the finger grooves around the edge
            with PolarLocations(radius=fluted_knob_diameter / 2, count=fluted_knob_flute_count):
                Circle(radius=fluted_knob_flute_radius, mode=Mode.SUBTRACT)
                
            # Flatten top and bottom tips so they don't hide the window
            Rectangle(fluted_knob_diameter + 2, fluted_knob_flat_distance, mode=Mode.INTERSECT)
                
            fillet(vertices(), radius=fluted_knob_fillet_radius)
                
        extrude(amount=fluted_knob_height)

        # 2. Cut the double-D hole for your modified move_rod peg
        with BuildSketch(Plane.XY):
            double_d_profile(clearance=fluted_knob_hole_clearance)
        # Leave 0.8mm of material at the top to hide the rod
        extrude(amount=fluted_knob_hole_depth, mode=Mode.SUBTRACT)
                
        # 3. Add a slight chamfer to the front face so it feels nice to touch
        chamfer(p.faces().sort_by(Axis.Z)[-1].edges(), length=fluted_knob_chamfer_length)

        # 4. Add indicator line on the front face (Y axis)
        with BuildSketch(Plane.XY.offset(fluted_knob_height)):
            Rectangle(fluted_knob_indicator_width, fluted_knob_diameter)
        extrude(amount=-fluted_knob_indicator_depth, mode=Mode.SUBTRACT)

    p.part.label = "fluted_knob"
    return p.part

