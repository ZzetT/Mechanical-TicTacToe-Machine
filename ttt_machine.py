def create_rack():
    """Creates the gear rack by meshing it automatically to a reference gear."""
    rack_teeth = 10
    rack_thickness = gear_thickness
    rack_obj = InvoluteRack(module=1, number_of_teeth=rack_teeth, height=rack_thickness)  
    rack_obj.mesh_to(create_gear(), target_dir=DOWN, backlash=0.2)

    rack_part = rack_obj.build_part() 
    
    with BuildPart() as rack_assembly:
        
        base_height = 2
        add(rack_part)
               
        rack_bbox = rack_part.bounding_box()
        with Locations((0, rack_bbox.min.Y, 0)):
            Box(
                rack_bbox.size.X, 
                base_height, 
                rack_bbox.size.Z, 
                align=(Align.CENTER, Align.MAX, Align.MIN)
            )
    
        # Add indicator box in the center of the rack's base
